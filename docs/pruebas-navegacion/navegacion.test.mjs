// Pruebas de lib/navegacion.js (direcciones #/ruta, permisos y títulos). Ejecutar: node docs/pruebas-navegacion/navegacion.test.mjs
import { PANTALLAS, PRINCIPALES, pantallaDesdeHash, hashDe, puedeVer, visiblesPara, tituloDocumento, pantallaDe } from "../../src/lib/navegacion.js";
let ok = 0, fallas = 0;
const eq = (n, a, b) => { const v = JSON.stringify(a) === JSON.stringify(b); v ? ok++ : fallas++; console.log((v ? "OK    " : "FALLA ") + n + (v ? "" : ` :: esperado ${JSON.stringify(b)} obtenido ${JSON.stringify(a)}`)); };
eq("8 pantallas, claves únicas", new Set(PANTALLAS.map((p) => p.key)).size, 8);
eq("rutas únicas", new Set(PANTALLAS.map((p) => p.ruta)).size, 8);
eq("cada pantalla tiene etiqueta, ícono, grupo y descripción", PANTALLAS.every((p) => p.label && p.icono && p.grupo && p.desc), true);
eq("barra inferior: Panel, Compras, Agenda, Alertas", PRINCIPALES, ["panel", "compras", "agenda", "notif"]);
eq("#/compras → compras", pantallaDesdeHash("#/compras"), "compras");
eq("#/alertas → notif", pantallaDesdeHash("#/alertas"), "notif");
eq("#/administracion → usuarios", pantallaDesdeHash("#/administracion"), "usuarios");
eq("acepta la clave interna (#/usuarios)", pantallaDesdeHash("#/usuarios"), "usuarios");
eq("mayúsculas y barra final", pantallaDesdeHash("#/Compras/"), "compras");
eq("con parámetros", pantallaDesdeHash("#/vendedores?x=1"), "vendedores");
eq("sin '/' (#gastos)", pantallaDesdeHash("#gastos"), "gastos");
eq("vacío → null", pantallaDesdeHash(""), null);
eq("solo # → null", pantallaDesdeHash("#/"), null);
eq("desconocida → null", pantallaDesdeHash("#/no-existe"), null);
eq("hashDe(notif)", hashDe("notif"), "#/alertas");
eq("hashDe(usuarios)", hashDe("usuarios"), "#/administracion");
eq("hashDe(desconocida) → panel", hashDe("x"), "#/panel");
eq("ida y vuelta para todas", PANTALLAS.every((p) => pantallaDesdeHash(hashDe(p.key)) === p.key), true);
eq("usuario no ve Administración", puedeVer("usuarios", false), false);
eq("administrador ve Administración", puedeVer("usuarios", true), true);
eq("usuario ve Vendedores", puedeVer("vendedores", false), true);
eq("pantalla inexistente no se ve", puedeVer("nada", true), false);
eq("visibles usuario (7)", visiblesPara(false).map((p) => p.key), ["panel", "compras", "agenda", "notif", "financiamiento", "vendedores", "gastos"]);
eq("visibles administrador (8)", visiblesPara(true).length, 8);
eq("título de pestaña", tituloDocumento("compras"), "Compras · BFK Ltda");
eq("título sin sesión", tituloDocumento(null), "BFK Ltda — Ventas Mercado Público");
eq("Administración es solo admin", pantallaDe("usuarios").adminOnly, true);
console.log(`\nRESUMEN pruebas navegación: ${ok} OK, ${fallas} FALLA(S)`);
process.exit(fallas ? 1 : 0);
